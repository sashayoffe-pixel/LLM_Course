#!/usr/bin/env node
// Regenerates the precache list and cache version in sw.js from the files on disk.
// Run after changing any course file:  node tools/build-sw.js   (validate.js checks it is up to date)
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
function list() {
  const out = ['./', 'index.html', 'manifest.webmanifest', 'icon.svg', 'core/engine.js', 'core/styles.css'];
  fs.readdirSync(path.join(root, 'sections')).sort().forEach(f => { if (/\.(js|css)$/.test(f)) out.push('sections/' + f); });
  return out;
}
function version(files) {
  const h = crypto.createHash('sha256');
  files.filter(f => f !== './').forEach(f => h.update(f + '\0' + fs.readFileSync(path.join(root, f))));
  return h.digest('hex').slice(0, 12);
}
function render() {
  const files = list(), v = version(files);
  const src = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
  return src.replace(/\/\/ <precache>[\s\S]*?\/\/ <\/precache>/,
    '// <precache> (generated by tools/build-sw.js — do not edit by hand)\nconst VERSION = \'' + v + '\';\nconst FILES = ' +
    JSON.stringify(files, null, 2).replace(/"/g, "'") + ';\n// </precache>');
}
module.exports = { render, list };
if (require.main === module) {
  const out = render(), p = path.join(root, 'sw.js');
  if (fs.readFileSync(p, 'utf8') === out) console.log('sw.js already up to date');
  else { fs.writeFileSync(p, out); console.log('sw.js updated'); }
}
